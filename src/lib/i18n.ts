/**
 * Helper to get the translated name of any sector in the target language
 */
export function getSectorName(sector: Sector | string, lang: LanguageCode): string {
  if (SECTOR_TRANSLATIONS[sector as Sector] && SECTOR_TRANSLATIONS[sector as Sector][lang]) {
    return SECTOR_TRANSLATIONS[sector as Sector][lang];
  }
  return sector;
}

/**
 * Helper to get a localized scheme title
 */
export function getLocalizedSchemeName(scheme: Scheme, lang: LanguageCode): string {
  if (lang === 'hi' && scheme.nameInHindi) return scheme.nameInHindi;
  if (lang === 'ta' && scheme.nameInTamil) return scheme.nameInTamil;
  if (lang === 'ml' && scheme.nameInMalayalam) return scheme.nameInMalayalam;
  if (lang === 'or' && scheme.nameInOdia) return scheme.nameInOdia;
  if (lang === 'ur' && scheme.nameInUrdu) return scheme.nameInUrdu;
  return scheme.name;
}
